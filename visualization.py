"""
This script creates pyvista interactive maps from the displacement vectors previously computed and saved to a pickled
 xarray.Dataset.
The visualizations are used to check the soundness of the displacement calculated in the BSplineTransform against
plots in literature. Moreover, screenshots of the interactive plots were included in the semester project thesis.

The functions plot_displ4() and plot_displ() have a significant overlap. In a Software Engineering project, one would
have applied some abstraction to reduce redundancy. For prototyping, however, the overhead is not justified.
"""
import pickle
import SimpleITK as sitk
import numpy as np
import xarray as xr
import pandas as pd
import pyvista as pv
from enum import Enum

"""
This enum class introduces axis descriptions that are concatenated in order of positive direction.
The symbolic names are mapped to the integer that corresponds to their index in the displacement
vector/magnitude lists in the xr.Dataset.
"""

class Axis(Enum):
    MEDIOLATERAL = 0
    ANTEROPOSTERIOR = 1
    INFEROSUPERIOR = 2
    MAGNITUDE = 3


signalVars = ['attenuation', 'fused', 'refraction', 'diffusion']
#.pkl file of the dataset generated by calcTfmsDenoised.py
dataset_mask = '' 

# Read pickled data back for local visualization
pkl_file = open(dataset_mask, 'rb')
data = pickle.load(pkl_file)
pkl_file.close()

pressures  = data.dP.values
n_iterations = data.Iterations.values
CpSpacing = data.CpSpacing.values

# Selection of grid hyperparameters to visualize
iter = n_iterations[-1]
type = signalVars[1]
display_axis = Axis.MEDIOLATERAL

def plot_displ4(data, pressures, type, iter, Axis, dataset_mask=""):
    """
    This function displays a 2x2 interactive plot, intended for a limited set of hyperparameters. The output was used for
    a presentation to avoid overloading the first slide displaying this type of plots.
    """

    scalar_bar_text = {Axis.MEDIOLATERAL: "Displacement mediolateral [µm]\n",
                       Axis.ANTEROPOSTERIOR: "Displacement anteroposterior [µm]\n",
                       Axis.INFEROSUPERIOR: "Displacement inferosuperior [µm]\n",
                       Axis.MAGNITUDE: "Displacement magnitude [µm]\n"
    }

    shape = (3, 2) 
    row_weights = [1, 1, 0.3]
    # Third column is half the size and fourth column is double size of the other columns
    col_weights = [1, 1]

    selP = [0, 3]
    selS = [3, 10]

    groups = [

        (0, 0),  # Second group spans over row 1-3 of the first column (0)
        (2, [0,1]),  # First group spans over all columns of the first row (0)
        (2, 1), 
    ]

    pl = pv.Plotter(shape=shape, row_weights=row_weights, col_weights=col_weights, groups=groups)
    for i, p in enumerate(selP):
        for j, s in enumerate(selS):
            meshDisp = data["mesh"].item().copy()
            meshDisp.point_data["val"] = data[f"meshPointDispl_{type}"].sel(dP=p, CpSpacing=s, Iterations=iter).values[:,Axis.value]
            pl.subplot(j, i)
            pl.add_text(f"{p} kPa, Control point spacing: {s} px", font_size = 16)
            pl.add_mesh(data["umboModel"].item(),
                        opacity=0.8
            )
            pl.add_mesh(meshDisp,
                         scalars="val",
                         clim = [0,600] if Axis == Axis.MAGNITUDE else [-600,600],
                         # viridis is a linear colormap suited for the magnitude, whereas the directional components require a diverging colormap
                         cmap = 'viridis' if Axis == Axis.MAGNITUDE else 'PiYG', 
                         show_scalar_bar = False,
                         opacity=0.99)

    pl.subplot(2,0)
    pl.add_text(
        f"Metric: MSE",#{dataset_mask}\nReconstruction: {type},\nIterations: {iter}
        position='left_edge',
        font_size=14)

    pl.subplot(2,1)
    pl.add_scalar_bar(
        scalar_bar_text[Axis],
        title_font_size=22,
        label_font_size=16,
        width=0.7,
        height = 0.8,
        position_x = 0.15,
        position_y = 0.15,
        fmt= "%.1f"
        )
    
    pl.link_views()  # link all the views
    pl.show()

def plot_displ(data, pressures, type, spacing, iter, Axis, dataset_mask=""):
    """
    This function displays a 3x3 interactive plot, intended to show the TM displacement at all 9 pressure levels.
    """

    scalar_bar_text = {Axis.MEDIOLATERAL: "Displacement mediolateral [µm]\n",
                       Axis.ANTEROPOSTERIOR: "Displacement anteroposterior [µm]\n",
                       Axis.INFEROSUPERIOR: "Displacement inferosuperior [µm]\n",
                       Axis.MAGNITUDE: "Displacement magnitude [µm]\n"
    }

    shape = (4, 3) 
    row_weights = [1, 1, 1, 0.5]
    # Third column is half the size and fourth column is double size of the other columns
    col_weights = [1, 1, 1]

    groups = [
        (0, 0),  # Second group spans over row 1-3 of the first column (0)
        (3, 2),  # First group spans over all columns of the first row (0)
    ]

    pl = pv.Plotter(shape=shape, row_weights=row_weights, col_weights=col_weights, groups=groups)
    for i, p in enumerate(pressures):
        meshDisp = data["mesh"].item().copy()
        meshDisp.point_data["val"] = data[f"meshPointDispl_{type}"].sel(dP=p, CpSpacing=spacing, Iterations=iter).values[:,Axis.value]
        pl.subplot(i // 3, i % 3)
        pl.add_text(f"{p} kPa", font_size = 26)
        pl.add_mesh(data["umboModel"].item(),
                    opacity=0.8
        )
        pl.add_mesh(meshDisp,
                     scalars="val",
                     clim = [0,600] if Axis == Axis.MAGNITUDE else [-600,600],
                     # viridis is a linear colormap suited for the magnitude, whereas the directional components require a diverging colormap
                     cmap = 'viridis' if Axis == Axis.MAGNITUDE else 'PiYG', 
                     show_scalar_bar = False,
                     opacity=0.99)


    pl.subplot(3,0)

    pl.add_text(
        f"Metric: MSE \nControl point spacing: {spacing}",#{dataset_mask}\nReconstruction: {type},\nIterations: {iter}
        position='left_edge',
        font_size=20)

    pl.subplot(3,2)
    pl.add_scalar_bar(
        scalar_bar_text[Axis],
        title_font_size=28,
        label_font_size=24,
        width=0.7,
        height = 0.8,
        position_x = 0.15,
        position_y = 0.15,
        fmt= "%.1f"
        )
    
    pl.link_views()  # link all the views
    pl.show()

for spacing in CpSpacing:
    plot_displ(data, pressures, type, spacing, iter, display_axis, dataset_mask)
